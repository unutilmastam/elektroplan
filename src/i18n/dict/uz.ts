/** Same shape as the Uzbek dictionary, with plain `string` values (so other languages can be typed against it). */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { readonly [K in keyof T]: Widen<T[K]> };
